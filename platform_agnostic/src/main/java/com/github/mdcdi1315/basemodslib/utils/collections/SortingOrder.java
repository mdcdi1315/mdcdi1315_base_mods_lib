package com.github.mdcdi1315.basemodslib.utils.collections;

/**
 * Provides the possible values that indicate with which
 * order the sorting algorithm should rearrange the
 * elements to be sorted.
 * @since 1.0.37
 */
public enum SortingOrder
{
    /**
     * Elements should be arranged with the first element having the least possible value.
     */
    ASCENDING,
    /**
     * Elements should be arranged with the first element having the maximum possible value.
     */
    DESCENDING
}
